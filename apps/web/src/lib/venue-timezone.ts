export interface ZoneGuess {
  readonly zone: string;
  /** False when the country has several zones and the city did not decide: ask the organizer. */
  readonly certain: boolean;
}

export function guessVenueZone(country: string, city: string | null | undefined): ZoneGuess | null {
  const cc = country.trim().toUpperCase();
  const multi = MULTI[cc];
  if (multi) {
    const hit = multi.cities[(city ?? '').trim().toLowerCase()];
    return hit ? { zone: hit, certain: true } : { zone: multi.fallback, certain: false };
  }
  const single = SINGLE[cc];
  return single ? { zone: single, certain: true } : null;
}
