/**
 * U11: regenerates the measured part of docs/ux/backlog.md from docs/ux/sweep/findings.json and
 * copies each listed page's screenshot next to it (docs/ux/sweep/backlog/). The reviewed findings
 * (the hand-written part above the marker) stay as they are.
 * Run: `node apps/web/e2e/ux-sweep/backlog.ts` after the sweep.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO } from './routes.ts';

interface Finding {
  app: 'web' | 'admin';
  pattern: string;
  width: number;
  metrics: {
    overflowX: number;
    nativeControls: number;
    smallTargets: number;
    smallTargetSamples: string[];
    h1: number;
    rawKeys: string[];
    longParagraphs: number;
    fields: number;
  };
  axe?: Record<'light' | 'dark', { id: string; nodes: number }[]>;
  consoleErrors: string[];
}

const SWEEP = join(REPO, 'docs/ux/sweep');
const BACKLOG = join(REPO, 'docs/ux/backlog.md');
const MARK = '<!-- measured: generated by apps/web/e2e/ux-sweep/backlog.ts -->';
const findings = JSON.parse(readFileSync(join(SWEEP, 'findings.json'), 'utf8')) as Finding[];
const slug = (app: string, p: string) => `${app}${p === '/' ? '-home' : p.replace(/[^a-zA-Z0-9]+/g, '-')}`;
mkdirSync(join(SWEEP, 'backlog'), { recursive: true });

/** Copies the page's shot (the width where it shows) and returns the committed relative path. */
function shot(app: string, pattern: string, width: number, theme = 'light'): string {
  const name = `${slug(app, pattern)}__${width}__${theme}.jpg`;
  const from = join(SWEEP, 'full', name);
  if (existsSync(from)) copyFileSync(from, join(SWEEP, 'backlog', name));
  return `sweep/backlog/${name}`;
}

interface Row {
  severity: 'high' | 'medium' | 'low';
  page: string;
  what: string;
  shot: string;
}
const rows: Row[] = [];
const seen = new Set<string>();
const add = (r: Row) => {
  const key = `${r.page}|${r.what}`;
  if (seen.has(key)) return;
  seen.add(key);
  rows.push(r);
};
const consoleNoise =
  /Cross-Origin-Opener-Policy|Failed to load resource: the server responded with a status of (?:404|401)|Blocked script execution/;

for (const f of findings) {
  const page = `${f.app}:${f.pattern}`;
  const m = f.metrics;
  if (f.width === 390 && m.overflowX > 0)
    add({
      severity: 'high',
      page,
      what: `Scrolls sideways at 390 px (${m.overflowX} px too wide)`,
      shot: shot(f.app, f.pattern, 390),
    });
  for (const theme of ['light', 'dark'] as const)
    for (const v of f.axe?.[theme] ?? [])
      add({
        severity: 'high',
        page,
        what: `axe ${v.id} in ${theme} mode (${v.nodes} elements)`,
        shot: shot(f.app, f.pattern, 1024, theme),
      });
  if (f.width === 1440 && m.nativeControls > 0)
    add({
      severity: 'medium',
      page,
      what: `${m.nativeControls} native select or date control outside packages/ui`,
      shot: shot(f.app, f.pattern, 1440),
    });
  if (f.width === 1440 && m.rawKeys.length > 0)
    add({
      severity: 'medium',
      page,
      what: `Shows raw identifiers (${m.rawKeys.slice(0, 2).join(', ')}) instead of words`,
      shot: shot(f.app, f.pattern, 1440),
    });
  if (
    f.width === 1440 &&
    m.smallTargets > 0 &&
    m.smallTargetSamples.some((s) => !s.includes('Skip to content'))
  )
    add({
      severity: 'low',
      page,
      what: `Targets under 24 px: ${m.smallTargetSamples
        .filter((s) => !s.includes('Skip to content'))
        .slice(0, 3)
        .join('; ')}`,
      shot: shot(f.app, f.pattern, 1440),
    });
  if (f.width === 1440 && m.fields > 12)
    add({
      severity: 'low',
      page,
      what: `${m.fields} fields on one screen: split into sections or steps`,
      shot: shot(f.app, f.pattern, 1440),
    });
  if (f.width === 1440 && m.longParagraphs > 2)
    add({
      severity: 'low',
      page,
      what: `${m.longParagraphs} long paragraphs: lead with numbers, move prose to a help panel`,
      shot: shot(f.app, f.pattern, 1440),
    });
  if (f.width === 1440)
    for (const e of f.consoleErrors.filter((x) => !consoleNoise.test(x)))
      add({
        severity: 'medium',
        page,
        what: `Console error: ${e.slice(0, 100)}`,
        shot: shot(f.app, f.pattern, 1440),
      });
}

const order = { high: 0, medium: 1, low: 2 } as const;
rows.sort((a, b) => order[a.severity] - order[b.severity] || a.page.localeCompare(b.page));
const table = [
  `Measured by the route sweep (${findings.filter((f) => f.width === 1440).length} routes). Severity: high = blocks use or fails an automated gate; medium = wrong or confusing; low = polish. The screenshot is under \`docs/ux/\`.`,
  '',
  '| Severity | Page | Finding | Screenshot |',
  '|---|---|---|---|',
  ...rows.map(
    (r) => `| ${r.severity} | \`${r.page}\` | ${r.what.replaceAll('|', '/')} | [shot](${r.shot}) |`,
  ),
  '',
];
const old = existsSync(BACKLOG) ? readFileSync(BACKLOG, 'utf8') : '';
const head = old.includes(MARK) ? old.slice(0, old.indexOf(MARK)) : old;
writeFileSync(BACKLOG, `${head}${MARK}\n\n${table.join('\n')}`);
process.stdout.write(`backlog: ${rows.length} measured rows\n`);
