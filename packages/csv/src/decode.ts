/**
 * Uploaded text files in whatever encoding a spreadsheet saved them (M4.1b): a byte-order mark
 * decides (UTF-8, UTF-16 LE/BE); otherwise strict UTF-8, and if that fails, Windows-1252 (what
 * Excel on Windows writes for "CSV" in Western locales). Never throws.
 */
export function decodeText(bytes: Uint8Array): string {
  if (bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf)
    return new TextDecoder('utf-8').decode(bytes.subarray(3));
  if (bytes[0] === 0xff && bytes[1] === 0xfe) return new TextDecoder('utf-16le').decode(bytes.subarray(2));
  if (bytes[0] === 0xfe && bytes[1] === 0xff) return new TextDecoder('utf-16be').decode(bytes.subarray(2));
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  } catch {
    return new TextDecoder('windows-1252').decode(bytes);
  }
}
